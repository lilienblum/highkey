// Writes the tables and columns Better Auth needs (for the plugins configured in
// apps/dashboard/src/server/auth/auth.ts) that migrations/ does not create yet, as the next
// numbered migration. Run it after adding or changing a Better Auth plugin:
//
//   bun apps/dashboard/scripts/auth-schema.ts <name>   e.g. … auth_organization
//
// It builds a scratch database from migrations/ and asks Better Auth what is missing, the way
// its CLI's `generate` does for the Kysely adapter.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { getMigrations } from "better-auth/db/migration";
import { createAuth } from "../src/server/auth/auth";
import { openBunDb } from "../src/server/db/bun-db";
import { applyMigrations, MIGRATIONS_DIR } from "../src/server/db/migrations";

const name = process.argv[2];
if (!name || !/^[a-z0-9_]+$/.test(name)) {
  console.error(
    "Usage: bun apps/dashboard/scripts/auth-schema.ts <name> (lowercase letters, digits, _)",
  );
  process.exit(1);
}
const db = openBunDb(":memory:");
await applyMigrations(db);
const auth = createAuth({
  database: { bun: db.raw },
  publicUrl: "http://localhost",
  secret: "schema-generation-secret-at-least-32-chars",
  mailer: null,
  signup: "invite",
});
const { compileMigrations } = await getMigrations(auth.options);
const sql = (await compileMigrations()).trim();
if (!sql) {
  console.log("migrations/ already has every table and column Better Auth needs.");
  process.exit(0);
}
const numbers = readdirSync(MIGRATIONS_DIR)
  .map((file) => /^(\d+)_/.exec(file)?.[1])
  .filter((n): n is string => n !== undefined)
  .map(Number);
const next = String(Math.max(0, ...numbers) + 1).padStart(4, "0");
const file = join(MIGRATIONS_DIR, `${next}_${name}.sql`);
writeFileSync(
  file,
  `-- Generated by apps/dashboard/scripts/auth-schema.ts from Better Auth's configuration; never edit once applied.\n${sql.endsWith(";") ? sql : `${sql};`}\n`,
);
console.log(`Wrote ${file}`);
